# Create a boolean variable
is_raining = True

if is_raining:
    print("It's raining! Don't forget your umbrella.")
else:
    print("It's not raining. Enjoy your day!")

############################################################

is_raining = False

if is_raining:
    print("It is still raining!)")
else:
    print("The rain has stopped. You can go outside now.")


